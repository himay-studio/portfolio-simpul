/**
 * Scans public/img and public/video and writes src/lib/asset-manifest.ts, a
 * plain object literal of every path that actually exists on disk right now.
 *
 * Why a generated manifest instead of an `fs.existsSync` check inside
 * Media.tsx: Media.tsx is imported from several "use client" components
 * (ProductCard, ProductDetail, CartDrawer, CheckoutFlow, SizeFinder), so
 * anything it imports ships into the browser bundle too. `node:fs` cannot be
 * bundled for the browser. A plain object literal can, so the filesystem
 * check happens here, once, at build/dev time, and Media.tsx only ever reads
 * a static map.
 *
 * Regenerated automatically via the `prebuild`/`predev` npm hooks, so it can
 * never drift from what Stage 4 actually landed in public/.
 */

import { writeFileSync, readdirSync, statSync } from "node:fs";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PUBLIC = join(ROOT, "public");

const found = [];

const walk = (dir) => {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name);
    if (entry.isDirectory()) walk(p);
    else if (statSync(p).size > 0) found.push(relative(PUBLIC, p).split("\\").join("/"));
  }
};

for (const sub of ["img", "video"]) {
  try {
    walk(join(PUBLIC, sub));
  } catch {
    // folder absent, nothing to add
  }
}

found.sort();

const body = `/**
 * GENERATED by scripts/gen-asset-manifest.mjs, do not hand edit.
 * One entry per file that exists under public/ at generation time, used by
 * Media.tsx to gate every image/video on the real filesystem instead of
 * trusting the data model.
 */

export const ASSETS: Record<string, true> = {
${found.map((p) => `  ${JSON.stringify(p)}: true,`).join("\n")}
};
`;

writeFileSync(join(ROOT, "src/lib/asset-manifest.ts"), body, "utf8");
console.log(`asset-manifest.ts written, ${found.length} files`);
